from pydantic import BaseModel, Field
from typing import List, Optional
from enum import Enum
from datetime import datetime


# ==========================================
# 1. INGESTION ENGINE SCHEMAS
# ==========================================

class RuleSeverity(str, Enum):
    CRITICAL = "CRITICAL"
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"

class PolicyRule(BaseModel):
    rule_id: str = Field(description="Unique identifier for the rule, e.g., RULE-CA-LABOR-01.")
    statute_reference: str = Field(description="Exact legal statute clause, e.g., CA Labor Code Sec 512.")
    description: str = Field(description="Summary of mandatory requirements under this rule.")
    severity: RuleSeverity = Field(description="Severity classification of violating this rule.")

class RuleSet(BaseModel):
    jurisdiction: str = Field(description="State or target jurisdiction (e.g., California, Federal).")
    document_title: str = Field(description="Title of the source legal/policy document.")
    extracted_rules: List[PolicyRule] = Field(description="List of structured policy rules parsed from text.")


# ==========================================
# 2. AUDITOR SUB-AGENT SCHEMAS
# ==========================================

class AuditStatus(str, Enum):
    PASSED = "PASSED"
    ACTION_REQUIRED = "ACTION_REQUIRED"
    NEEDS_REVIEW = "NEEDS_REVIEW"

class ViolationItem(BaseModel):
    violation_id: str = Field(description="Unique ID for tracking this violation.")
    law_reference: str = Field(description="The specific statute or rule clause violated.")
    target_component: str = Field(description="Target file, database column, or policy section affected.")
    severity: RuleSeverity = Field(description="Impact severity rating.")
    issue_description: str = Field(description="Detailed explanation of non-compliance.")

class ComplianceReport(BaseModel):
    policy_id: str = Field(description="ID of the audited operational policy or system asset.")
    status: AuditStatus = Field(description="Overall compliance result.")
    violations: List[ViolationItem] = Field(default_factory=list, description="List of detected violations.")
    remediation_summary: str = Field(description="High-level plan to fix the detected violations.")


# ==========================================
# 3. REMEDIATION SUB-AGENT (SELF-HEALING) SCHEMAS
# ==========================================

class PatchStatus(str, Enum):
    DRAFT = "DRAFT"
    VALIDATED = "VALIDATED"
    FAILED_VALIDATION = "FAILED_VALIDATION"
    PENDING_APPROVAL = "PENDING_APPROVAL"

class PatchPayload(BaseModel):
    patch_id: str = Field(description="Unique identifier for the generated patch.")
    target_file: str = Field(description="Path or identifier of the file to patch.")
    original_snippet: str = Field(description="Original non-compliant code or policy snippet.")
    proposed_patch: str = Field(description="Corrected code/text patch generated by agent.")
    validation_status: PatchStatus = Field(description="Current validation lifecycle status.")
    retry_count: int = Field(default=0, description="Number of self-healing retries executed by the agent.")
    validator_feedback: Optional[str] = Field(default=None, description="Stack trace or status from validator tool.")


# ==========================================
# 4. MEMORY BANK & OBSERVABILITY SCHEMAS
# ==========================================

class ToolCallLog(BaseModel):
    tool_name: str
    input_params: dict
    output_result: str
    was_error: bool = False
    timestamp: str = Field(default_factory=lambda: datetime.utcnow().isoformat())

class AgentExecutionTrace(BaseModel):
    session_id: str = Field(description="Session identifier for state persistence.")
    policy_id: str = Field(description="Operational asset being audited.")
    agent_name: str = Field(description="Name of the executing Google ADK agent.")
    current_state: str = Field(description="State graph position (e.g., AUDITING, HEALING, HITL_PAUSE).")
    tool_logs: List[ToolCallLog] = Field(default_factory=list)
    self_healing_attempts: int = Field(default=0, description="Explicit metric for self-correction occurrences.")
    compliance_report: Optional[ComplianceReport] = None
    patch_payload: Optional[PatchPayload] = None
    created_at: str = Field(default_factory=lambda: datetime.utcnow().isoformat())


# ==========================================
# 5. GATEKEEPER & HITL SCHEMAS
# ==========================================

class ApprovalDecision(str, Enum):
    APPROVED = "APPROVED"
    REJECTED = "REJECTED"
    ESCALATED = "ESCALATED"

class ApprovalActionPayload(BaseModel):
    session_id: str
    patch_id: str
    decision: ApprovalDecision
    reviewed_by: str = Field(default="ComplianceAdmin")
    comments: Optional[str] = None
    timestamp: str = Field(default_factory=lambda: datetime.utcnow().isoformat())