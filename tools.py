# ==========================================
# 2. CODE & POLICY PATCH VALIDATION TOOL (Self-Healing Engine)
# ==========================================

def code_patch_validator(patch_code: str) -> str:
    """
    Validates the structural syntax, regulatory tags, and schema safety of a proposed 
    policy or code patch generated by the Remediation Agent.
    
    Demonstrates autonomous self-healing:
    - Attempt 1: Fails with an explicit validation error trace.
    - Attempt 2: Succeeds after the Remediation Agent parses the trace and updates its patch.
    
    Args:
        patch_code (str): The proposed code snippet or policy markdown patch.
        
    Returns:
        str: Validation status message ("SUCCESS..." or "ERROR...").
    """
    TOOL_METRICS["patch_validation_attempts"] += 1
    attempt_number = TOOL_METRICS["patch_validation_attempts"]
    
    # Required statutory tag that the agent MUST include to pass governance rules
    REQUIRED_TAG = "[STATUTORY-COMPLIANCE-TAG: CA-LABOR-SEC512]"
    
    # --- DEMONSTRATION SELF-HEALING TRIGGER ---
    # First attempt deliberately fails if statutory tag is missing or on first invocation
    if attempt_number == 1 or REQUIRED_TAG not in patch_code:
        return (
            f"ERROR 422 (SCHEMA VALIDATION FAILED) [Attempt #{attempt_number}]:\n"
            f"The proposed patch was rejected by the enterprise gatekeeper rule engine.\n"
            f"Reason: Missing required statutory compliance header tag: '{REQUIRED_TAG}'.\n"
            f"Action Required: Insert '{REQUIRED_TAG}' at the top of the proposed patch block "
            f"and fix Section 2.1 rest break interval from 5 hours to 4 hours."
        )
    
    # --- SUCCESSFUL VALIDATION ---
    TOOL_METRICS["self_healing_corrections"] += 1
    return (
        f"SUCCESS [Attempt #{attempt_number}]: "
        f"Patch syntax and statutory tag '{REQUIRED_TAG}' verified against Enterprise Governance Schema v2.1. "
        f"Status set to VALIDATED."
    )


